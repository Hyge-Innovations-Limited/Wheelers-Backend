const fenceOn = () => (process.env['SERVICE_AREA'] ?? 'lagos').trim().toLowerCase() !== 'off';

/** Is this point inside Lagos State? (Ray casting over the outline.) */
export function isInLagos(lat: number, lng: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  let inside = false;
  for (let i = 0, j = LAGOS_OUTLINE.length - 1; i < LAGOS_OUTLINE.length; j = i++) {
    const [latI, lngI] = LAGOS_OUTLINE[i]!;
    const [latJ, lngJ] = LAGOS_OUTLINE[j]!;
    if (latI > lat !== latJ > lat && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI) inside = !inside;
  }
  return inside;
}

/** Inside the area Wheelers serves right now (always true with the fence lifted). */
export function isInServiceArea(lat: number, lng: number): boolean {
  return !fenceOn() || isInLagos(lat, lng);
}

/** The first of these points outside the service area, or null when every one is in. */
export function firstOutsideServiceArea<T extends { lat: number; lng: number }>(points: Array<T | null | undefined>): T | null {
  for (const point of points) if (point && !isInServiceArea(point.lat, point.lng)) return point;
  return null;
}
